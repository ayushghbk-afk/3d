import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

export async function setupSql() {
  const dir = new URL('../supabase/migrations/', import.meta.url);
  const files = (await readdir(dir)).filter((name) => name.endsWith('.sql')).sort();
  const sections = await Promise.all(files.map(async (name) => `-- Migration: ${name}\n${await readFile(new URL(name, dir), 'utf8')}`));
  return `-- GENERATED by npm run supabase:setup; edit the migrations, not this file.
-- FRESH INSTALLATIONS ONLY. Paste this whole file into the Supabase SQL editor.
-- On an existing installation, apply only the migrations you have not run yet.
-- This transaction prevents an unsuccessful setup from leaving half-created tables.
-- No credentials belong in this SQL. Row Level Security remains enabled.

begin;

${sections.join('\n')}\ncommit;\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('../supabase/setup.sql', import.meta.url), await setupSql());
  console.log('Wrote supabase/setup.sql for a fresh Supabase project.');
}
